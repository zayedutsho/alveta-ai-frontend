import {getCliClient} from 'sanity/cli'
import {loadEnv} from 'vite'
import {resolve} from 'node:path'

const projectId = 'iwd3xpdu'
const name = 'Alveta marketing — Vercel production'
const filter = '_type == "landingPage" && _id == "Oh6YgvMTqh9o5H57ty0iDS"'
const environment = loadEnv('development', resolve(process.cwd(), '..'), 'VERCEL_DEPLOY_HOOK_URL')
const deployUrl = environment.VERCEL_DEPLOY_HOOK_URL

async function main() {
  if (!deployUrl) {
    console.log('Setup ready. Add VERCEL_DEPLOY_HOOK_URL to the frontend .env.local file. No webhook was created.')
    return
  }
  const target = new URL(deployUrl)
  if (target.protocol !== 'https:' || target.hostname !== 'api.vercel.com' || target.username || target.password || !/^\/v1\/integrations\/deploy\/[^/]+\/[^/]+\/?$/.test(target.pathname)) {
    throw new Error('Expected the HTTPS Deploy Hook URL generated by Vercel. The supplied value was not printed or used.')
  }
  if (process.env.SANITY_DEPLOY_HOOK_APPLY !== '1') {
    console.log(JSON.stringify({name, dataset: 'production', destinationHost: target.hostname, filter, drafts: false, versions: false, mode: 'dry-run'}, null, 2))
    return
  }
  const client = getCliClient({apiVersion: '2025-08-15'})
  const hooks = await client.request<{name: string; url: string; dataset: string; includeDrafts?: boolean; rule?: {filter?: string}}[]>({url: `/hooks/projects/${projectId}`, useGlobalApi: true})
  const existing = hooks.find(hook => hook.name === name || hook.url === deployUrl)
  if (existing) {
    if (existing.url === deployUrl && existing.dataset === 'production' && !existing.includeDrafts && existing.rule?.filter === filter) {
      console.log('The matching production deploy webhook is already configured. No changes made.')
      return
    }
    throw new Error('An existing webhook uses this name or destination. Review it in Sanity Manage before changing it; nothing was overwritten.')
  }
  await client.request({url: `/hooks/projects/${projectId}`, useGlobalApi: true, method: 'POST', body: {
    type: 'document', name, url: deployUrl, dataset: 'production', apiVersion: 'v2025-08-15',
    description: 'Rebuild the Vercel production branch when the published Alveta landing page changes.',
    httpMethod: 'POST', includeDrafts: false, includeAllVersions: false, isDisabledByUser: false,
    rule: {on: ['create', 'update', 'delete'], filter, projection: '{_id, _rev}'},
  }})
  console.log('Production publish webhook configured. The deploy URL was kept private. No deployment was triggered by this setup command.')
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
